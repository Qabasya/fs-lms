<?php

declare( strict_types=1 );

namespace Inc\Shared\Traits;

/**
 * Trait AnswerNormalizer
 *
 * Единая нормализация короткого ответа перед сверкой с эталоном (Tasks.md, п. 4):
 * регистр не важен, пробельные символы не важны ВООБЩЕ — «Макс: 2; 3»,
 * «Макс:2;3» и «Макс:\n2;3» это один и тот же ответ. Ученик набирает ответ
 * руками, эталон приходит из меты задания, и расхождение в одном пробеле не
 * должно стоить балла.
 *
 * Принятое следствие: ответ, где пробел разделял два значения («1159 57»),
 * засчитывается и слитно («115957»). Схлопывание пробелов вместо удаления
 * такого поведения не даёт и требование задачи не покрывает.
 *
 * Метод статический намеренно: его зовут и DI-объекты (чекеры,
 * {@see \Inc\Services\Course\BatchCheckService}), и статический
 * {@see \Inc\Services\Task\FillTextParser::checkGap()}. Отдельная статическая
 * утилита-класс сюда не заводится — список разрешённых закрыт (CLAUDE.md).
 *
 * Нормализует ТОЛЬКО сравниваемое значение. Ответ, который показывают ученику
 * и преподавателю, хранится и выводится сырым — с его пробелами и переносами.
 *
 * @package Inc\Shared\Traits
 */
trait AnswerNormalizer {

	/**
	 * Приводит ответ к сравнимому виду: нижний регистр без пробельных символов.
	 *
	 * `\s` с модификатором `/u` покрывает пробел, табуляцию, CR/LF и юникодные
	 * пробелы (в т.ч. неразрывный) — отдельный список символов не нужен.
	 */
	protected static function normalizeAnswer( string $value ): string {
		return mb_strtolower( (string) preg_replace( '/\s+/u', '', $value ) );
	}
}
