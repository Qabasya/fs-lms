declare( strict_types=1 );

namespace Inc\Modules\EgeComputer\Config;

/**
 * Class OgeInstructionConfig
 *
 * Текст вкладки «i» экрана экзамена станции ОГЭ — дословно из
 * `.docs/oge/oge-screens/exam-1-screen.md` (2026-08-18, согласовано с
 * пользователем: 16 заданий, файлы — результат заданий 13-16). Отделён от
 * рендера — та же роль, что {@see KegeInstructionConfig} у ЕГЭ, но содержание
 * другое (инструкция по выполнению работы, а не конвенции логических
 * обозначений — у ОГЭ по информатике таких конвенций в заданиях нет).
 *
 * @package Inc\Modules\EgeComputer\Config
 */
class OgeInstructionConfig {

	/**
	 * Заголовок + абзацы инструкции по порядку показа.
	 *
	 * @return array<int, array{text: string, indent: bool}>
	 */
	public static function paragraphs(): array {
		$plain = static fn( string $text ): array => [ 'text' => $text, 'indent' => false ];

		return [
			$plain( 'Основной государственный экзамен по ИНФОРМАТИКЕ' ),
			$plain( 'Инструкция по выполнению работы' ),
			$plain( 'Экзаменационная работа состоит из 16 заданий. На выполнение работы по информатике отводится 2,5 часа (150 минут).' ),
			$plain( 'В заданиях 1–12 запишите в ответе число, слово, последовательности букв или цифр.' ),
			$plain( 'Результатом выполнения каждого из заданий 13–16 является отдельный файл. Формат файла, его имя и каталог для сохранения Вам сообщат организаторы экзамена.' ),
			$plain( 'Баллы, полученные Вами за выполненные задания, суммируются. Постарайтесь выполнить как можно больше заданий и набрать наибольшее количество баллов.' ),
			$plain( 'Рекомендуем после завершения работы вернуться к заданиям и проверить ответы.' ),
			$plain( 'Желаем успеха!' ),
		];
	}
}
