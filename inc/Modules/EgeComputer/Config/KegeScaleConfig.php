<?php

declare( strict_types=1 );

namespace Inc\Modules\EgeComputer\Config;

/**
 * Class KegeScaleConfig
 *
 * Официальные правила подсчёта баллов КЕГЭ по информатике: сколько позиций
 * ответа даёт задание и как первичный балл переводится во вторичный (тестовый).
 *
 * Живут в модуле, а не на работе ({@see \Inc\DTO\Assessment\AssessmentDTO::$scoreMap}):
 * станция имитирует реальный КЕГЭ, у которого шкала фиксирована приказом —
 * максимум вторичного балла всегда 100, и авторская таблица перевода его не
 * меняет. Générique-экран результата ({@see \Inc\Services\Assessment\AttemptResultService})
 * по-прежнему считает по таблице работы — ядро об этих правилах не знает.
 *
 * @package Inc\Modules\EgeComputer\Config
 */
class KegeScaleConfig {

	/**
	 * Шкала перевода первичного балла во вторичный (тестовый).
	 * 0 присутствует явно: без него пустая работа осталась бы без вторичного балла.
	 */
	private const SCALE = [
		0  => 0,
		1  => 7,
		2  => 14,
		3  => 20,
		4  => 27,
		5  => 34,
		6  => 40,
		7  => 43,
		8  => 46,
		9  => 48,
		10 => 51,
		11 => 54,
		12 => 56,
		13 => 59,
		14 => 62,
		15 => 64,
		16 => 67,
		17 => 70,
		18 => 72,
		19 => 75,
		20 => 78,
		21 => 80,
		22 => 83,
		23 => 85,
		24 => 88,
		25 => 90,
		26 => 93,
		27 => 95,
		28 => 98,
		29 => 100,
	];

	/**
	 * Номер задания => сколько ответов оно требует. Всё, чего здесь нет, — один
	 * ответ. Задания №26 и №27 дают по два ответа, и первичный балл начисляется
	 * за каждый: отсюда 29 первичных баллов на 27 заданиях работы.
	 */
	private const MULTI_ANSWER = [
		26 => 2,
		27 => 2,
	];

	/**
	 * Номера заданий с табличным (многоячеечным) ответом станции — единый
	 * источник для `exam.php` (какая панель ответа рендерится),
	 * `kege-exam.js::tableShapeFor()` (форма таблицы на клиенте, своя копия —
	 * делить JS/PHP-константу негде) и {@see EgeComputerModule::resolveTableAnswer()}
	 * (расшифровка сериализованного ответа на экране «Работы» учителя).
	 * №26/№27 дают по 2 первичных балла ({@see MULTI_ANSWER}); №17/№18/№20/№25 —
	 * тот же ввод чисто для удобства (может быть больше одного числа в ответе),
	 * позиция как была одним слотом, так и осталась.
	 *
	 * @var int[]
	 */
	public const TABLE_TASK_NUMBERS = [ 17, 18, 20, 25, 26, 27 ];

	/**
	 * Таблица перевода для {@see \Inc\Services\Assessment\SecondaryScoreService}.
	 *
	 * @return array<int, int>
	 */
	public static function scale(): array {
		return self::SCALE;
	}

	/** Максимальный вторичный балл — всегда 100. */
	public static function secondaryMax(): int {
		return max( self::SCALE );
	}

	/**
	 * Сколько позиций ответа занимает задание в листе ответов. Оно же —
	 * максимальный первичный балл задания: балл начисляется за каждый ответ.
	 *
	 * @param int $taskNumber Номер задания КИМ (0 — номер не определён)
	 */
	public static function answerSlots( int $taskNumber ): int {
		return self::MULTI_ANSWER[ $taskNumber ] ?? 1;
	}
}