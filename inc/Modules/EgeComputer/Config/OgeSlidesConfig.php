<?php

declare( strict_types=1 );

namespace Inc\Modules\EgeComputer\Config;

/**
 * Class OgeSlidesConfig
 *
 * Слайды инструкции станции ОГЭ — карусель `kege/entry.php`, тот же экран, что
 * у {@see KegeSlidesConfig}, но первый слайд у ОГЭ — ТЕКСТ (шаги ритуала сдачи
 * экзамена из `.docs/oge/oge-screens/1-sreen.md`), а не картинка, как у ЕГЭ.
 * Остальные 8 слайдов — скриншоты реального интерфейса ОГЭ (те же условия, что
 * у {@see KegeSlidesConfig::slides()}: контент отделён от рендера, `entry.php`
 * просто перебирает массив и рендерит слайд по его `type`).
 *
 * Бланк регистрации и код активации — ОБЩИЕ с ЕГЭ (решено с пользователем
 * 2026-08-18): `blankHint()` здесь не заводится, `EgeComputerModule` для обоих
 * kind резолвит {@see KegeSlidesConfig::blankHint()}.
 *
 * @package Inc\Modules\EgeComputer\Config
 */
class OgeSlidesConfig {

	/** Каталог картинок инструкции относительно корня плагина — общий с КЕГЭ. */
	private const IMAGE_DIR = 'inc/Modules/EgeComputer/assets/images/';

	/**
	 * Шаги ритуала сдачи экзамена (текстовый первый слайд) — дословно из
	 * `.docs/oge/oge-screens/1-sreen.md`.
	 *
	 * @return array<int, array{title: string, text: string}>
	 */
	private static function ritualSteps(): array {
		return [
			[
				'title' => '1. Ввод номера бланка регистрации',
				'text'  => 'На данном этапе Вам необходимо ввести в систему номер бланка регистрации.',
			],
			[
				'title' => '2. Ознакомление с инструкцией',
				'text'  => 'На данном этапе Вам предлагается ознакомиться с инструкцией по выполнению заданий.',
			],
			[
				'title' => '3. Регистрация участника',
				'text'  => 'На данном этапе Вам необходимо проверить правильность номера бланка регистрации, '
					. 'внесённого в систему. В случае ошибки необходимо изменить номер бланка регистрации. '
					. 'Если всё верно, необходимо дождаться организатора для подтверждения корректности '
					. 'введённого номера бланка регистрации.',
			],
			[
				'title' => '4. Активация экзамена',
				'text'  => 'На данном этапе Вам необходимо ввести код активации экзамена, который сообщит организатор.',
			],
			[
				'title' => '5. Прохождение экзамена',
				'text'  => 'На данном этапе Вам необходимо выполнить задания, используя программное обеспечение, '
					. 'установленное на компьютере, и ввести ответы на задания с помощью клавиатуры. Вы можете '
					. 'выполнять задания в любом удобном для Вас порядке.',
			],
			[
				'title' => '6. Завершение экзамена',
				'text'  => 'На данном этапе Вам предлагается перенести контрольную сумму, автоматически '
					. 'сформированную на основе введённых Вами ответов в систему, в бланк регистрации.',
			],
		];
	}

	/**
	 * Слайды инструкции по порядку показа — первый ТЕКСТОВЫЙ (`type: 'text'`),
	 * остальные картинки (`type: 'image'`, тот же контракт полей, что у
	 * {@see KegeSlidesConfig::slides()}).
	 *
	 * @return array<int, array{type: string, title?: string, steps?: array, image?: string, alt?: string, width?: int, height?: int}>
	 */
	public static function slides(): array {
		$imageSlides = [
			[ 'oge-instruction-2.webp', 'Инструкция к заданиям КИМ: состав и время выполнения работы', 1541, 1073 ],
			[ 'oge-instruction-3.webp', 'Вкладка «i»: инструкция к КИМ доступна во время экзамена', 1057, 639 ],
			[ 'oge-instruction-4.webp', 'Экран экзамена: боковое меню, область задания и область ответа', 1541, 1073 ],
			[ 'oge-instruction-5.webp', 'Боковое меню заданий: список и отметки о данных ответах', 1541, 1074 ],
			[ 'oge-instruction-6.webp', 'Информация об экзамене и элементы управления', 1541, 1075 ],
			[ 'oge-instruction-7.webp', 'Область ввода краткого ответа', 1542, 1073 ],
			[ 'oge-instruction-8.webp', 'Подтверждение досрочного завершения экзамена', 1074, 628 ],
			[ 'oge-instruction-9.webp', 'Страница завершения экзамена и контрольная сумма', 1529, 1064 ],
		];

		$slides = [
			[ 'type' => 'text', 'title' => 'Процесс сдачи экзамена включает следующие основные этапы', 'steps' => self::ritualSteps() ],
		];

		foreach ( $imageSlides as $slide ) {
			$slides[] = [
				'type'   => 'image',
				'image'  => self::imageUrl( $slide[0] ),
				'alt'    => $slide[1],
				'width'  => $slide[2],
				'height' => $slide[3],
			];
		}

		return $slides;
	}

	/**
	 * Публичный адрес картинки станции.
	 *
	 * @param string $file Имя файла в каталоге картинок
	 */
	private static function imageUrl( string $file ): string {
		return plugins_url( self::IMAGE_DIR . $file, FS_LMS_PATH . 'fs-lms.php' );
	}
}
