<?php

declare( strict_types=1 );

namespace Inc\Modules\EgeComputer\Config;

/**
 * Class KegeInstructionConfig
 *
 * Текст вкладки «i» экрана экзамена — соглашения к заданиям КИМ (обозначения
 * логических связок, равносильность, приоритеты операций, единицы измерения).
 * Дословная выдержка из инструкции настоящей станции, поэтому правится целыми
 * пунктами и живёт рядом со слайдами инструкции ({@see KegeSlidesConfig}), а не
 * в шаблоне: контент отделён от рендера.
 *
 * Разметка минимальна и фиксирована — абзац плюс необязательная втяжка
 * (`.kege-ind` для пунктов a)…f), которые несут собственную литеру и потому
 * остаются абзацами, а не списком). Шаблон экранирует текст сам.
 *
 * @package Inc\Modules\EgeComputer\Config
 */
class KegeInstructionConfig {

	/**
	 * Пункты инструкции по порядку показа.
	 *
	 * @return array<int, array{text: string, indent: bool}>
	 */
	public static function paragraphs(): array {
		$plain = static fn( string $text ): array => [ 'text' => $text, 'indent' => false ];
		$inset = static fn( string $text ): array => [ 'text' => $text, 'indent' => true ];

		return [
			$plain( 'В заданиях используются следующие соглашения.' ),
			$plain( '1. Обозначения для логических связок (операций):' ),
			$inset( 'a) отрицание (инверсия, логическое НЕ) обозначается ¬ (например, ¬А);' ),
			$inset( 'b) конъюнкция (логическое умножение, логическое И) обозначается ∧ (например, А ∧ В) либо & (например, А & В);' ),
			$inset( 'c) дизъюнкция (логическое сложение, логическое ИЛИ) обозначается ∨ (например, А ∨ В) либо | (например, А | В);' ),
			$inset( 'd) следование (импликация) обозначается → (например, А → В);' ),
			$inset( 'e) тождество обозначается ≡ (например, A ≡ B); выражение A ≡ B истинно тогда и только тогда, когда значения A и B совпадают (либо они оба истинны, либо они оба ложны);' ),
			$inset( 'f) символ 1 используется для обозначения истины (истинного высказывания); символ 0 – для обозначения лжи (ложного высказывания).' ),
			$plain( '2. Два логических выражения, содержащие переменные, называются равносильными (эквивалентными), если значения этих выражений совпадают при любых значениях переменных. Так, выражения А → В и (¬А) ∨ В равносильны, а А ∨ В и А ∧ В неравносильны (значения выражений разные, например, при А = 1, В = 0).' ),
			$plain( '3. Приоритеты логических операций: инверсия (отрицание), конъюнкция (логическое умножение), дизъюнкция (логическое сложение), импликация (следование), тождество. Таким образом, ¬А ∧ В ∨ С ∧ D означает то же, что и ((¬А) ∧ В) ∨ (С ∧ D). Возможна запись А ∧ В ∧ С вместо (А ∧ В) ∧ С. То же относится и к дизъюнкции: возможна запись А ∨ В ∨ С вместо (А ∨ В) ∨ С.' ),
			$plain( '4. Обозначения Мбайт и Кбайт используются в традиционном для информатики смысле – как обозначения единиц измерения, соотношение которых с единицей «байт» выражается степенью двойки.' ),
		];
	}
}
