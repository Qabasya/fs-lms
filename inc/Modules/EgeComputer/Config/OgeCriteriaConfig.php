	/**
	 * Собирает HTML рубрики из уровней (балл + описание), от высшего к низшему.
	 * Экранирование — `wp_kses_post`-совместимый набор тегов (`<strong>`, `<br>`);
	 * текст статичен (не пользовательский ввод), поэтому санитайз не требуется
	 * на этом шаге — вызывающий код передаёт готовый HTML в шаблон как есть,
	 * как и `WorkDetailService::condition()` для условия задачи.
	 *
	 * @param array<int, array{0: int, 1: string}> $tiers [балл, описание]
	 */
	private static function tiers( array $tiers ): string {
		$rows = array_map(
			static fn( array $tier ): string => sprintf(
				'<div class="fs-oge-rubric__tier"><span class="fs-oge-rubric__score">%d балл%s</span><span class="fs-oge-rubric__desc">%s</span></div>',
				$tier[0],
				1 === $tier[0] ? '' : ( $tier[0] >= 2 && $tier[0] <= 4 ? 'а' : 'ов' ),
				$tier[1]
			),
			$tiers
		);

		return implode( '', $rows );
	}
